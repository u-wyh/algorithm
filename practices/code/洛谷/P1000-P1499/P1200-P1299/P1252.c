// https://www.luogu.com.cn/problem/P1252
// 题意：5 名队员参加 25 km 接力赛，
// 每人跑一次且跑 [1, 10] 内的整数公里数。
// 题意：已知每人连续跑 1..10 km 的各自用时（单位公里用时不加快），
// 求最短总用时及分配方案。
// 输入：共 5 行，
// 每行 10 个正整数表示该队员连续跑 1..10 km 的总用时。
// 输出：第一行输出最短总用时，
// 第二行输出 5 个整数表示 1..5 号队员各自跑的公里数。
// 数据范围：固定 5 人总长 25 km，每项时间均为不超过 10^7 的正整数。
// 算法标签：贪心
#include <stdio.h>

int minx = 2147483647, flag, ans; // 定义最小值，标志变量和最小路程
int a[5][11], b[5][11], c[5]; // 3个数组

int main() { // 过程华丽开始
    for (int i = 0; i < 5; i++) {
        c[i] = 1; // 注意，初值为1
        for (int j = 1; j < 11; j++) {
            scanf("%d", &a[i][j]); // 读入
            b[i][j] = a[i][j] - a[i][j - 1]; // 计算
        }
    }

    for (int i = 0; i < 20; i++) {
        minx = 2147483647; // 每次更新初始值
        for (int j = 0; j < 5; j++) {
            if (b[j][c[j] + 1] < minx && c[j] + 1 <= 10) { // 如果比目前最小值小，且没有超过10km
                flag = j; // 标志
                minx = b[j][c[j] + 1]; // 最小值更新
            }
        }
        c[flag]++; // 增加
    }

    ans = 0; // 初始化ans
    for (int i = 0; i < 5; i++) {
        ans += a[i][c[i]]; // 计算最优解
    }

    printf("%d\n%d %d %d %d %d\n", ans, c[0], c[1], c[2], c[3], c[4]); // 完美输出
    return 0; // 过程华丽结束
}
