// https://www.luogu.com.cn/problem/P9412
// 题意：有 n 种面值硬币 1 = a_1 < a_2 < ... < a_n，
// 且满足 a_{i+1} 是 a_i 的倍数。
// 定义购买价格为 x 的商品所需的最小硬币数为 f(x)（不能找零）。
// 求最小的整数 m，使得 f(m) < f(m-1)；
// 不存在输出 -1。
// 题意：第一行输入 n，第二行输入 a_1..a_n；
// 输出一行一个整数 m 或 -1。
// 数据范围：
// 1 <= n <= 10，
// 1 = a_1 < a_2 < ... < a_n <= 10^9，
// a_{i+1} 为 a_i 倍数。
// 难度评分：1000（洛谷分级换算）
// 算法标签：线性扫描
#include <stdio.h>

int n, a[15];

int main() {
    scanf("%d", &n); // 读取n的值
    for (int i = 0; i < n; i++) { // 注意数组索引从0开始
        scanf("%d", &a[i]); // 读取数组元素
    }

    for (int i = 1; i < n; i++) { // 从第二个元素开始检查
        if (a[i] != a[i - 1] + 1) { // 检查是否不是连续递增
            printf("%d\n", a[i]); // 输出第一个不连续递增的元素
            return 0; // 退出程序
        }
    }

    printf("-1\n"); // 如果所有元素都是连续递增的，则输出-1
    return 0;
}
