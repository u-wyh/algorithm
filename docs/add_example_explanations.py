def main() -> None:
    explanations = {}
    for row in ENTRIES.splitlines():
        name, task, idea = row.split("|", 2)
        if name in explanations:
            raise ValueError(f"重复的文件名：{name}")
        explanations[name] = (task, idea)
    used = set()
    updated = 0
    for path in ROOT.rglob("*.cpp"):
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        link_at = next((i for i, line in enumerate(lines[:12]) if line.startswith("// 例题：")), None)
        if link_at is None:
            continue
        if path.stem not in explanations:
            raise ValueError(f"缺少例题解释：{path}")
        used.add(path.stem)
        if any(line.startswith("// 题意：") for line in lines[:12]):
            continue
        task, idea = explanations[path.stem]
        eol = "\r\n" if lines[link_at].endswith("\r\n") else "\n"
        lines[link_at + 1:link_at + 1] = [f"// 题意：{task}{eol}", f"// 思路：{idea}{eol}"]
        path.write_text("".join(lines), encoding="utf-8", newline="")
        updated += 1
    unused = set(explanations) - used
    if unused:
        raise ValueError(f"无对应链接文件：{sorted(unused)}")
    print(f"example_explanations={len(used)} updated={updated}")


if __name__ == "__main__":
    main()
