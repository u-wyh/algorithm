// https://www.luogu.com.cn/problem/P3205
// 题意：输入人数 n，
// 以及一个长度为 n 的理想身高序列 h_1..h_n（所有身高互不相同）。
// 初始队列按任意顺序依次将每人插入当前队形：第 1 人直接放中间；
// 之后每人若比前一个插入的人高则插到当前队形最右端，否则插到最左端。
// 输出有多少种不同的初始排队顺序能得到给定的理想队形，
// 结果对 19650827 取模。
// 数据范围：n <= 1000，1000 <= h_i <= 2000。
// 算法标签：区间动态规划
#include <stdio.h>

#define MOD 19650827

int f[2010][2010][2], a[2010];

int main() {
    int n;
    scanf("%d", &n);
    for (int i = 1; i <= n; i++) {
        scanf("%d", &a[i]);
    }

    // 初始化长度为1的子序列
    for (int i = 1; i <= n; i++) {
        f[i][i][0] = 1;
    }

    // 动态规划计算子序列个数
    for (int len = 1; len <= n; len++) {
        for (int i = 1, j = i + len; j <= n; i++, j++) {
            if (a[i] < a[i + 1]) {
                f[i][j][0] = (f[i][j][0] + f[i + 1][j][0]) % MOD;
            }
            if (a[i] < a[j]) {
                f[i][j][0] = (f[i][j][0] + f[i + 1][j][1]) % MOD;
            }
            if (a[j] > a[i]) {
                f[i][j][1] = (f[i][j][1] + f[i][j - 1][0]) % MOD;
            }
            if (a[j] > a[j - 1]) {
                f[i][j][1] = (f[i][j][1] + f[i][j - 1][1]) % MOD;
            }
        }
    }

    // 输出结果
    printf("%d\n", (f[1][n][0] + f[1][n][1]) % MOD);

    return 0;
}
