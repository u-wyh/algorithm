// https://www.luogu.com.cn/problem/P8144
// 题意：数轴上有 6 枚棋子摆放在严格递增坐标 a_1..a_6，
// 其中第 1, 2, 5, 6 枚为黑子，第 3, 4 枚为白子。
// 指定先手 c ∈ {B, W} 后双方轮流操作：
// 每次选一枚己方棋子向左或向右移动 1 步；
// 若目标位置恰有 1 枚对方棋子则将其移除，
// 若目标位置有 >= 2 枚对方棋子则不可移动至此；
// 同位置允许有任意多枚己方棋子。
// 无合法移动者判负。
// 双方在己方不输的前提下尽可能使对方输且均取最优策略，判断游戏是否会无限进行下去。
// 第一行输入 T，接下来 T 行每行字符 c 和 6 个整数 a_1..a_6。
// 输出 T 行，无限进行输出 Yes，否则输出 No。
// 数据范围：1 <= T <= 10^5，
// |a_i| <= 10^9，c ∈ {B, W}，a 严格单调递增。
// 算法标签：博弈论、分类讨论
#include<bits/stdc++.h>
using namespace std;

int pos[7];

int main()
{
    int T;
    cin>>T;
    while(T--){
        char c;
        cin>>c>>pos[1]>>pos[2]>>pos[3]>>pos[4]>>pos[5]>>pos[6];
        if ((c=='W')&& ((pos[3]-pos[2]==1&&pos[2]-pos[1]>1)||(pos[5]-pos[4]==1&&pos[6]-pos[5]>1))
            &&(!(pos[3]-pos[2]==1&&pos[5]-pos[4]==1)))
			 std::cout<<"Yes\n";
		else std::cout<<"No\n";
    }
    return 0;
}
